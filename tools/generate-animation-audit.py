# The existing helper combines a local matrix with its parent in place. Verify
# the complete 4x4 product independently, including aliased output.
generated=generated.replace('\tsub_82703748(ctx, base);',r'''
  {
    const uint32_t destination=ctx.r5.u32;
    std::array<float,16> left{},right{},actual{};
    for(uint32_t i=0;i<16;++i) {
      left[i]=std::bit_cast<float>(REX_LOAD_U32(ctx.r3.u32+i*4));
      right[i]=std::bit_cast<float>(REX_LOAD_U32(ctx.r4.u32+i*4));
    }
    sub_82703748(ctx,base);
    for(uint32_t i=0;i<16;++i)actual[i]=std::bit_cast<float>(REX_LOAD_U32(destination+i*4));
    for(uint32_t row=0;row<4;++row)for(uint32_t col=0;col<4;++col) {
      float expected=0;for(uint32_t k=0;k<4;++k)expected+=left[row*4+k]*right[k*4+col];
      if(std::abs(actual[row*4+col]-expected)>0.00001f*(1+std::abs(expected)))
        REXLOG_ERROR("[hierarchy-mismatch] destination={:08X} row={} col={} actual={} expected={}",destination,row,col,actual[row*4+col],expected);
    }
  }
''')
needle='\t__restgprlr_23(ctx, base);'
generated=generated.replace(needle,needle+r'''
  std::ofstream audit("V:/logs/animation-vector-audit.bin",std::ios::binary);
  audit.write(reinterpret_cast<const char*>(records.data()),records.size()*sizeof(Record));
  REXLOG_INFO("[animation-audit] records={} bytes={}",records.size(),records.size()*sizeof(Record));
''',1)
(root/'port/src/animation_audit.cpp').write_text(prefix+generated+'\n')
